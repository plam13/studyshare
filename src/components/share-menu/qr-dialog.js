import { Modal } from 'bootstrap';
import { escapeHtml } from '../../utils/dom.js';
import { saveBlob } from '../../utils/download.js';
import { showError } from '../../utils/toast.js';

/** File-friendly name from a title (keeps Cyrillic letters). */
const fileBase = (title) => title.replace(/[^\p{L}\p{N}]+/gu, '-').replace(/^-|-$/g, '').slice(0, 60) || 'studyshare';

/**
 * Modal with a QR code for `url` (e.g. to show a material on a projector or share it in class).
 * The QR library is loaded only when the dialog is opened.
 */
export async function openQrDialog({ url, title }) {
  const wrapper = document.createElement('div');
  wrapper.innerHTML = `
    <div class="modal fade" tabindex="-1" aria-labelledby="ss-qr-title" aria-modal="true" role="dialog">
      <div class="modal-dialog modal-dialog-centered modal-sm">
        <div class="modal-content">
          <div class="modal-header">
            <h2 class="modal-title h5" id="ss-qr-title"><i class="bi bi-qr-code me-2" aria-hidden="true"></i>QR код</h2>
            <button type="button" class="btn-close" data-bs-dismiss="modal" aria-label="Затвори"></button>
          </div>
          <div class="modal-body text-center">
            <div class="ss-qr-box mb-3" data-qr role="img" aria-label="QR код към ${escapeHtml(title)}">
              <div class="spinner-border text-primary" role="status"><span class="visually-hidden">Генериране…</span></div>
            </div>
            <p class="small fw-semibold mb-1 text-break">${escapeHtml(title)}</p>
            <p class="small text-secondary mb-0 text-break">${escapeHtml(url)}</p>
          </div>
          <div class="modal-footer">
            <button type="button" class="btn btn-outline-secondary" data-bs-dismiss="modal">Затвори</button>
            <button type="button" class="btn btn-primary" data-qr-download disabled>
              <i class="bi bi-download me-1" aria-hidden="true"></i>Изтегли PNG
            </button>
          </div>
        </div>
      </div>
    </div>`;
  const element = wrapper.firstElementChild;
  document.body.append(element);
  const modal = new Modal(element);

  const closeOnNavigation = () => modal.hide();
  window.addEventListener('popstate', closeOnNavigation, { once: true });
  element.addEventListener('hidden.bs.modal', () => {
    window.removeEventListener('popstate', closeOnNavigation);
    modal.dispose();
    element.remove();
  }, { once: true });
  modal.show();

  try {
    const QRCode = (await import('qrcode')).default;
    const options = { errorCorrectionLevel: 'M', margin: 2, color: { dark: '#1f1f1f', light: '#ffffff' } };
    // SVG markup is generated by the library from the URL only (no user HTML)
    element.querySelector('[data-qr]').innerHTML = await QRCode.toString(url, { ...options, type: 'svg' });
    const download = element.querySelector('[data-qr-download]');
    download.disabled = false;
    download.addEventListener('click', async () => {
      const dataUrl = await QRCode.toDataURL(url, { ...options, width: 768 });
      saveBlob(await (await fetch(dataUrl)).blob(), `QR-${fileBase(title)}.png`);
    });
  } catch {
    modal.hide();
    showError('QR кодът не можа да бъде генериран.');
  }
}
